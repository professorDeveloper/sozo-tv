import Foundation
assert(PlaybackSourcePolicy.playableURL("https://media.test/file.m3u8?token=abc", type: nil) != nil)
assert(PlaybackSourcePolicy.playableURL("https://media.test/signed/opaque", type: "hls") != nil)
assert(PlaybackSourcePolicy.playableURL("https://media.test/e/abcdef", type: "iframe") == nil)
assert(PlaybackSourcePolicy.playableURL("https://media.test/file.mpd", type: nil) == nil)
assert(PlaybackSourcePolicy.playableURL("https://media.test/page", type: nil) == nil)
assert(PlaybackSourcePolicy.playableURL("file:///private/video.mp4", type: "mp4") == nil)
assert(PlaybackSourcePolicy.playableURL("https://user:secret@media.test/file.mp4", type: nil) == nil)
let merged = PlaybackSourcePolicy.headers(base: ["Referer": "base", "Cookie": "a=b"], source: ["referer": "override", "Unsafe": "x\ny"])
assert(merged["referer"] == "override" && merged["Referer"] == nil && merged["Cookie"] == "a=b" && merged["Unsafe"] == nil)
let options = [VideoSource(quality: "720p", videoUrl: "https://media.test/a.mp4", type: "mp4", isDefault: true, headers: nil), VideoSource(quality: "720p duplicate", videoUrl: "https://media.test/a.mp4", type: "mp4", isDefault: false, headers: nil), VideoSource(quality: "embed", videoUrl: "https://media.test/e/a", type: "iframe", isDefault: false, headers: nil)]
assert(PlaybackSourcePolicy.unique(options).count == 1)
print("Playback sources: supported formats, iframe/DASH/opaque rejection, credentials, headers and deduplication passed")
let fullHD = VideoSource(quality: "1080p", videoUrl: "https://media.test/full.mp4", type: "mp4", isDefault: true, headers: nil)
let hd = VideoSource(quality: "720p", videoUrl: "https://media.test/hd.mp4", type: "mp4", isDefault: false, headers: nil)
let sd = VideoSource(quality: "480p", videoUrl: "https://media.test/sd.mp4", type: "mp4", isDefault: false, headers: nil)
assert(PlaybackSourcePolicy.constrained([fullHD, sd, hd], maximumHeight: 720, dataSaver: false).map(\.quality) == ["720p", "480p"])
assert(PlaybackSourcePolicy.constrained([fullHD, sd, hd], maximumHeight: nil, dataSaver: true).first?.quality == "480p")
assert(PlaybackSourcePolicy.constrained([fullHD], maximumHeight: 480, dataSaver: false).isEmpty)
let adaptive = VideoSource(quality: "1080p Auto", videoUrl: "https://media.test/master.m3u8", type: "hls", isDefault: true, headers: nil)
assert(PlaybackSourcePolicy.constrained([adaptive], maximumHeight: 720, dataSaver: false).count == 1)
assert(PlaybackSourcePolicy.height(VideoSource(quality: "Server 4K", videoUrl: "https://a.test/v.mp4", type: nil, isDefault: nil, headers: nil)) == 2160)
print("Quality policies: progressive cap, data-saver order, no compatible source and adaptive delegation passed")
let legacyMovie = try! JSONDecoder().decode(EpisodePage.self, from: Data(#"{"isSerial":false,"episodes":[],"videoSources":[],"playerSrc":"https://media.test/opaque","type":"hls","headers":{"Referer":"https://catalogue.test"},"subtitles":[{"label":"English","file":"https://media.test/en.vtt"}]}"#.utf8))
assert(legacyMovie.movieEnvelope.videoSources?.first?.videoUrl == "https://media.test/opaque")
assert(legacyMovie.movieEnvelope.videoSources?.first?.type == "hls")
assert(legacyMovie.movieEnvelope.headers?["Referer"] == "https://catalogue.test")
assert(legacyMovie.movieEnvelope.subtitles?.count == 1)
let partial = try! JSONDecoder().decode(EpisodePage.self, from: Data(#"{"episodes":[{"episode":12.5,"mediaRef":"special"},{"episode":"13","mediaRef":"normal"},{"episode":null,"mediaRef":"unknown"}],"type":"hls","headers":{"Origin":"https://catalogue.test"},"videoSources":[{"videoUrl":"https://media.test/opaque","headers":{"Referer":"override"}}]}"#.utf8))
assert(partial.episodes?.first?.episode == nil && partial.episodes?.first?.label == "Episode 12.5")
assert(partial.episodes?[1].episode == 13 && partial.episodes?[2].episode == nil)
assert(partial.movieEnvelope.videoSources?.first?.type == "hls")
assert(partial.movieEnvelope.headers?["Origin"] == "https://catalogue.test")
print("Movie endpoint playerSrc/type/headers/subtitles and fractional/null/string episode decoding passed")
let inherited = try! JSONDecoder().decode(MediaEnvelope.self, from: Data(#"{"type":"hls","videoSources":[{"videoUrl":"https://media.test/signed-stream","quality":"Auto"}]}"#.utf8))
assert(PlaybackSourcePolicy.unique(inherited.playbackSources).count == 1)
assert(PlaybackSourcePolicy.preferred([fullHD, hd], quality: "720p").first?.videoUrl == hd.videoUrl)
assert(PlaybackSourcePolicy.preferred([hd], quality: "1080p").first?.videoUrl == hd.videoUrl)
print("Inherited serial source format and remembered compatible source preference passed")
var normalStart = PlaybackStartupState(autoPlay: true)
assert(normalStart.becameReady(needsResume: false) == .play)
assert(normalStart.becameReady(needsResume: false) == .none)
var completedResume = PlaybackStartupState(autoPlay: true)
assert(completedResume.becameReady(needsResume: true) == .seek)
assert(completedResume.resumeCompleted(success: true) == .play)
assert(completedResume.resumeCompleted(success: true) == .none)
var resumeStart = PlaybackStartupState(autoPlay: true)
assert(resumeStart.becameReady(needsResume: true) == .seek)
resumeStart.enteredBackground()
assert(resumeStart.resumeCompleted(success: true) == .none, "Background during resume must cancel automatic Play")
assert(resumeStart.resumeCompleted(success: true) == .none)
var backgroundStart = PlaybackStartupState(autoPlay: true)
backgroundStart.enteredBackground()
assert(backgroundStart.becameReady(needsResume: false) == .none)
var manualStart = PlaybackStartupState(autoPlay: false)
assert(manualStart.becameReady(needsResume: true) == .seek)
assert(manualStart.resumeCompleted(success: true) == .none)
var canceledStart = PlaybackStartupState(autoPlay: true)
assert(canceledStart.becameReady(needsResume: true) == .seek)
assert(canceledStart.resumeCompleted(success: false) == .none)
var destroyedStart = PlaybackStartupState(autoPlay: true)
assert(destroyedStart.becameReady(needsResume: true) == .seek)
destroyedStart.finish()
assert(destroyedStart.resumeCompleted(success: true) == .none)
print("Playback startup: background interruption, manual start, failed seek and destroyed-player callbacks passed")

var transientInactive = PlaybackStartupState(autoPlay: true)
assert(transientInactive.apply(transientInactive.becameReady(needsResume: false), activity: .inactive) == .none)
assert(transientInactive.becameActive() == .play, "Initial transient inactive must defer rather than discard startup Play")
assert(transientInactive.becameActive() == .none)
var inactiveThenBackground = PlaybackStartupState(autoPlay: true)
assert(inactiveThenBackground.apply(inactiveThenBackground.becameReady(needsResume: false), activity: .inactive) == .none)
inactiveThenBackground.enteredBackground()
assert(inactiveThenBackground.becameActive() == .none)
var inactiveResume = PlaybackStartupState(autoPlay: true)
assert(inactiveResume.becameReady(needsResume: true) == .seek)
assert(inactiveResume.apply(inactiveResume.resumeCompleted(success: true), activity: .inactive) == .none)
assert(inactiveResume.becameActive() == .play)
var inactiveThenFinish = PlaybackStartupState(autoPlay: true)
assert(inactiveThenFinish.apply(inactiveThenFinish.becameReady(needsResume: false), activity: .inactive) == .none)
inactiveThenFinish.finish()
assert(inactiveThenFinish.becameActive() == .none)
print("Playback startup: transient inactive defers once; background and teardown discard deferred Play")
