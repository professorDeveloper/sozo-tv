import Foundation

let adult = ProfileContentScope(profile: "household:adult", path: "auth/favorites")
let kids = ProfileContentScope(profile: "household:kids", path: "auth/favorites")
precondition(adult != kids, "A profile switch invalidates visible library data even at the same endpoint")
precondition(adult != ProfileContentScope(profile: adult.profile, path: "auth/lists/watched"))
var inbox = InboxPagination()
precondition(inbox.begin(reset: true) == 1)
inbox.succeeded(page: 1, totalPages: 3)
precondition(inbox.retryResets, "A mark-read failure must refresh, not skip to another page")
precondition(inbox.begin(reset: false) == 2)
precondition(!inbox.retryResets)
precondition(inbox.begin(reset: inbox.retryResets) == 2, "Failed page 2 retries page 2")
inbox.succeeded(page: 2, totalPages: 3)
inbox.prepareRefreshRetry()
precondition(inbox.begin(reset: inbox.retryResets) == 1)
inbox.reset()
precondition(inbox.page == 0 && !inbox.hasMore && inbox.retryResets)
print("PASS: profile-scoped content invalidation; failed inbox page retries; mutation retry refreshes")
